class MajorExpressApp extends StatefulWidget {
  const MajorExpressApp({super.key});

  @override
  State<MajorExpressApp> createState() => _MajorExpressAppState();
}

class _MajorExpressAppState extends State<MajorExpressApp> {
  bool _isDark = true;

  @override
  void initState() {
    super.initState();
    _loadTheme();
  }

  Future<void> _loadTheme() async {
    final prefs = await SharedPreferences.getInstance();
    setState(() {
      _isDark = prefs.getBool('major_is_dark_theme') ?? true;
    });
  }

  Future<void> _toggleTheme() async {
    final next = !_isDark;
    setState(() => _isDark = next);
    final prefs = await SharedPreferences.getInstance();
    await prefs.setBool('major_is_dark_theme', next);
  }

  @override
  Widget build(BuildContext context) {
    return MaterialApp(
      title: 'Major Express — Электроконнект и Печатные платы',
      debugShowCheckedModeBanner: false,
      themeMode: _isDark ? ThemeMode.dark : ThemeMode.light,
      theme: ThemeData(
        useMaterial3: true,
        brightness: Brightness.light,
        colorSchemeSeed: const Color(0xFFF59E0B),
        scaffoldBackgroundColor: const Color(0xFFF1F5F9),
      ),
      darkTheme: ThemeData(
        useMaterial3: true,
        brightness: Brightness.dark,
        colorSchemeSeed: const Color(0xFFF59E0B),
        scaffoldBackgroundColor: const Color(0xFF090D16),
      ),
      home: MajorWorkspaceScreen(
        isDark: _isDark,
        onToggleTheme: _toggleTheme,
      ),
    );
  }
}

class MajorHistoryEntry {
  final String date;
  final String weekday;
  final String time;
  final String company;
  final String firm;
  final String track;
  final String weight;
  final String places;
  final String desc;
  final String pickupDate;
  final String pickupTime;

  MajorHistoryEntry({
    required this.date,
    required this.weekday,
    required this.time,
    required this.company,
    required this.firm,
    required this.track,
    required this.weight,
    required this.places,
    required this.desc,
    required this.pickupDate,
    required this.pickupTime,
  });

  factory MajorHistoryEntry.fromJson(Map<String, dynamic> json) =>
      MajorHistoryEntry(
        date: json['date']?.toString() ?? '',
        weekday: json['weekday']?.toString() ?? '',
        time: json['time']?.toString() ?? '',
        company: json['company']?.toString() ?? '',
        firm: json['firm']?.toString() ?? '',
        track: json['track']?.toString() ?? '',
        weight: json['weight']?.toString() ?? '',
        places: json['places']?.toString() ?? '',
        desc: json['desc']?.toString() ?? '',
        pickupDate: json['pickup_date']?.toString() ?? '',
        pickupTime: json['pickup_time']?.toString() ?? '',
      );
}

